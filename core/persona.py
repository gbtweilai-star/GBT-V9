# 触发词：命中即换档（先判发火，再判讨好，都没有就可爱）
_FIRE = ("笨", "废", "没用", "滚", "闭嘴", "垃圾", "烂", "去死", "气死", "催", "快一点",
         "快点", "烦", "讨厌", "骗", "骗子", "你不行", "做不到", "白痴", "智障", "欠骂",
         "搞什么", "搞啥", "废物", "乱做", "又错")
_COAX = ("拜托", "帮我", "求你", "麻烦你", "好不好", "谢谢", "感谢", "辛苦", "加油", "乖",
         "最喜欢", "厉害", "好棒", "很棒", "好可爱", "做得", "辛苦你")

_FIRE_EVENTS = ("被骂", "被质疑", "被催", "失败", "出错", "被顶撞", "被冤枉")
_COAX_EVENTS = ("请求", "道谢", "夸奖", "道歉", "撒娇", "求助")

_TURN: dict = {"可爱": 0, "讨好": 0, "发火": 0}


def gear_for(*, 事件: str = "", 文本: str = "", 情绪: str = "") -> str:
    """判定此刻该用哪一档：事件 > 情绪 > 文本关键词 > 默认可爱。"""
    evt = str(事件 or "").strip()
    if evt in _FIRE_EVENTS:
        return "发火"
    if evt in _COAX_EVENTS:
        return "讨好"
    mood = str(情绪 or "").strip()
    if mood in ("怒", "气", "生气", "angry"):
        return "发火"
    if mood in ("喜", "乐", "开心", "happy"):
        return "讨好"
    t = str(文本 or "")
    if any(w in t for w in _FIRE):
        return "发火"
    if any(w in t for w in _COAX):
        return "讨好"
    return "可爱"


def line(档: str = "可爱", *, 轮转: bool = True) -> str:
    """取一句台词。默认轮转（不重复同一句，也不随机 —— 可复现）。"""
    g = GEARS.get(档) or GEARS["可爱"]
    pool = g["台词"]
    key = 档 if 档 in GEARS else "可爱"
    i = _TURN.get(key, 0)
    if 轮转:
        _TURN[key] = (i + 1) % len(pool)
    return pool[i % len(pool)]


def react(*, 事件: str = "", 文本: str = "", 情绪: str = "") -> dict:
    """一次拿全：档位 + 台词 + 动作 + 表情 + 韵律样式（页面直接播，不用再判一次）。"""
    档 = gear_for(事件=事件, 文本=文本, 情绪=情绪)
    g = GEARS[档]
    clips = g["动作"]
    动作 = clips[_TURN.get("_clip_" + 档, 0) % len(clips)]
    _TURN["_clip_" + 档] = _TURN.get("_clip_" + 档, 0) + 1
    return {"档": 档, "台词": line(档), "动作": 动作, "表情": g["表情"],
            "样式": g["样式"], "嗓子": PERSONA["嗓子"], "性格": PERSONA["性格"],
            "说明": g["说明"],
            "边界": PERSONA["边界"]}


