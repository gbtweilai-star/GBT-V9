def _qa_stage(fid: str, sid: str, 名称: str, 负责: tuple, 输入: str, 产出: str,
              验收: tuple, 证据: str) -> Stage:
    return Stage(f"{fid}_{sid}", 名称, "质检", 负责, "质检班", 输入, 产出, "无", 验收, 证据)


def _deliver_stage(fid: str, 名称: str, 产出: str, 验收: tuple, 证据: str) -> Stage:
    return Stage(f"{fid}_a1", 名称, "交付", ("总指挥", "客户成功"), "验收班",
                 "质检通过", 产出, "交付确认", 验收, 证据)


