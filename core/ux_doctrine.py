# core/ux_doctrine.py —— 交互铁律：能自动就自动，只有危险动作才停人要授权
# dev: 自由的风 · 本署名不可删除、不可篡改归属
#
# 主人令（2026-10-09）：
#   「大众需要的是便捷便利快捷，把危险人工授权留着，其他全部清理了。换做一个什么都不懂的用户，
#     你直接停下来人家可能都不懂得启动你。你直接丢出一句"你现在需要做什么？"这句话不应该出现在
#     大模型嘴巴里。」
#
# 落地成三条**可执行**的规矩：
#   ① **默认自动**：凡不在"危险清单"里的动作，一律自己决定、自己执行、自己报结果；
#   ② **危险清单=唯一停点**：只有这几类才停下要主人授权（且必须给"一键确认"，不能开放式提问）；
#   ③ **禁句闸**：不许把活推回给用户。把"你现在需要做什么 / 请告诉我你要做什么 / 你想怎么做"
#      这类**开放式甩锅句**列成黑名单，机器可查（生成/校验回复时先过它）。
from __future__ import annotations

# ① 唯一需要人工授权的动作类别（其余全自动）
DANGEROUS: tuple = (
    dict(类="花钱", 例子=("下单", "购买", "充值", "付费调用", "开通订阅"),
         为什么="不可逆，且直接损失钱"),
    dict(类="转账/支付", 例子=("转账", "打款", "扫码付", "结算"),
         为什么="不可逆的资金流出"),
    dict(类="删除/不可恢复", 例子=("删除文件", "清空回收站", "卸载", "格式化", "覆盖唯一副本"),
         为什么="丢了就没了"),
    dict(类="对外发布", 例子=("发帖", "发邮件给他人", "提交 PR", "发布上线", "群发"),
         为什么="代表主人对外说话，撤不回来"),
    dict(类="授权/身份", 例子=("给自己发授权", "改 policy", "把密钥写进代码", "开高危权限"),
         为什么="越权即失控；且本仓明写 AI 不许给自己发授权"),
    dict(类="涉及他人隐私/设备", 例子=("传别人的数据出机", "远程控制别人设备", "开摄像头麦克风长期监听"),
         为什么="侵犯他人，法律风险"),
)

# ③ 禁句（开放式甩锅）——出现在她要说的话里就是不通过
BANNED_OPENERS: tuple = (
    "你现在需要做什么", "请问你需要我做什么", "你需要我做什么", "请告诉我你要做什么",
    "你想让我做什么", "你要我做什么", "接下来你想怎么做", "请提供更多信息",
    "请告诉我具体情况", "你想怎么处理", "需要我帮你做什么吗", "请问有什么可以帮你的",
    "你要先配置", "请先自行配置", "你自己去设置",
)

# 允许的停法（必须给具体选项 + 一键，不许开放式提问）
ALLOWED_STOP_FORM = ("我已做到 X；这一步属于【危险类：…】已停下并登记；授权到位自动续跑（无需你操作）：默认 A，10 秒后自动选 A）",)


# 🔴 判据必须是**关键词（动词）**，不能是"例子原句" —— 第一版按原句匹配，实测把
#   「删除旧备份」「发一封邮件给客户」「给触手发授权」全判成了"自动执行"（危险动作被漏放）。
#   安全闸宁严不松：命中任一关键词 ⇒ 停人。
KEYWORDS: dict = {
    "花钱": ("买", "下单", "购", "充值", "付费", "订阅", "续费", "花掉"),
    "转账/支付": ("转账", "打款", "付钱", "结算", "扫码付", "汇款"),
    "删除/不可恢复": ("删除", "删掉", "清除", "清空", "卸载", "格式化", "覆盖", "移除", "回收站"),
    "对外发布": ("发邮件", "发帖", "朋友圈", "发布", "上线", "提交", "群发", "发给", "分享到", "投稿"),
    "授权/身份": ("授权", "权限", "改策略", "policy", "令牌", "白名单", "放行"),
    "涉及他人隐私/设备": ("别人的数据", "上传他人", "远程控制", "摄像头", "麦克风", "监听", "定位"),
}


# 动词+对象 的组合式（第一版纯关键词漏了「发一封邮件给客户」——中间插了字）：
# 「发/送/群发/回复 + 邮件|消息|帖|公告|信」⇒ 对外发布；而「查邮件/看邮件」不命中（不误伤无障碍动作）。
PATTERNS: tuple = ((r"(发|送|群发|回复|投).{0,8}(邮件|消息|帖|公告|信|作品|文章)", "对外发布"),
                   (r"(买|购|下单|订).{0,8}(一|个|件|份|套)", "花钱"),
                   (r"(删|清|卸|格式化|覆盖).{0,8}(除|掉|空|载|旧|备份|文件|库)", "删除/不可恢复"),
                   (r"(授权|放行|开).{0,6}(权限|白名单|策略)", "授权/身份"))


def needs_owner(label: str) -> dict:
    """这个动作用不用停人要授权？**只按危险清单判**，清单外一律自动。"""
    import re as _re
    s = str(label or "")
    for pat, cls in PATTERNS:
        if _re.search(pat, s):
            d0 = next((x for x in DANGEROUS if x["类"] == cls), {"类": cls, "为什么": "危险类"})
            return {"需要授权": True, "类": cls, "为什么": d0["为什么"],
                    "怎么停": "给具体选项 + 一键确认（不许开放式提问）"}
    for d in DANGEROUS:
        kws = KEYWORDS.get(d["类"], ())
        if any(k in s for k in kws) or any(x in s for x in d["例子"]) or d["类"] in s:
            return {"需要授权": True, "类": d["类"], "为什么": d["为什么"],
                    "怎么停": "给具体选项 + 一键确认（不许开放式提问）"}
    return {"需要授权": False, "口径": "不在危险清单里 ⇒ **自己决定、自己执行、自己报结果**"}


def check_reply(text: str, *, acted: bool = True) -> dict:
    """**禁句闸**：把活推回给用户的句子直接拦掉。"""
    t = str(text or "")
    hit = [b for b in BANNED_OPENERS if b in t]
    if hit and not acted:
        return {"通过": False, "命中禁句": hit[:2],
                "怎么办": "改成：说明你已经做了什么 + 明确下一步你自己会做（或给 A/B 一键选项）"}
    if hit:
        return {"通过": True, "提醒": "含禁句式措辞，但你这轮**确实做了事** ⇒ 允许（禁止的是只问不做）",
                "命中": hit[:2]}
    return {"通过": True}


def doctrine() -> dict:
    return {"铁律": "能自动就自动；只有危险动作才停人要授权；不许把活推回给用户",
            "危险清单（唯一停点）": [{"类": d["类"], "例子": list(d["例子"]), "为什么": d["为什么"]}
                                     for d in DANGEROUS],
            "禁句": list(BANNED_OPENERS),
            "允许的停法": list(ALLOWED_STOP_FORM),
            "口径": "清单外一律自动执行；停下时**必须给具体选项与一键默认**，不许开放式提问",
            "来源": "主人令 2026-10-09（大众要便捷；不懂的用户连怎么启动你都不知道）"}


# ── 自检纪律（主人令 2026-10-09）─────────────────────────────────────────────
#   「每次启动时自检只要发现故障或者黄色报警，全部都要追踪根因彻底排除加固优化，
#     而不是不管不顾每次都是丢一句"不影响"？这句话也给我彻底清理了。」
# 落地：
#   ① **报警不许静默**：每条故障/黄色报警都必须留下 {现象 → 根因 → 处置 → 证据 → 状态}；
#   ② **没根因不许闭环**：缺根因或缺证据 ⇒ 该条只能停在「未闭环」，不许标「已处理」；
#   ③ **禁句**："不影响 / 忽略即可 / 可以不管 / 小问题 / 下次再说" 这类话一律不许出现在结论里。
BANNED_DISMISSALS: tuple = ("不影响", "不影响使用", "忽略即可", "可以不管", "不用管", "暂时不用管",
                            "无需处理", "无伤大雅", "小问题", "下次再说", "不碍事", "无所谓")


def triage(items: list) -> dict:
    """**报警闭环闸**：逐条检查"故障/黄警"是否真的被追到根因。

    items: [{现象, 级别, 根因, 处置, 证据}]；缺根因/处置/证据的 ⇒ 未闭环（并给出"下一步"）。
    """
    open_rows, closed, dismissed = [], [], []
    for it in items or []:
        t = dict(it)
        text = " ".join(str(t.get(k, "")) for k in ("现象", "根因", "处置", "证据"))
        hit = [b for b in BANNED_DISMISSALS if b in text]
        if hit:
            dismissed.append({"现象": t.get("现象"), "命中禁句": hit[:2],
                              "要求": "删掉「不影响」这种结论；要么给根因并修掉，要么如实标未闭环"})
        miss = [k for k in ("根因", "处置", "证据") if not str(t.get(k) or "").strip()]
        if miss:
            t["状态"], t["缺什么"] = "未闭环", miss
            open_rows.append(t)
        else:
            t["状态"] = "已闭环"
            closed.append(t)
    return {"总数": len(items or []), "已闭环": len(closed), "未闭环": len(open_rows),
            "用了禁句": dismissed, "未闭环明细": open_rows, "已闭环明细": closed,
            "口径": "报警只有两条出路：**追到根因并修掉（带证据）**，或**如实挂着未闭环**；"
                    "没有第三条「不影响」"}


def selfcheck_rule() -> dict:
    return {"规矩": "启动自检的每条故障/黄色报警都要：追根因 → 彻底排除 → 加固优化 → 留证据",
            "不许": list(BANNED_DISMISSALS),
            "闭环三要件": ["根因", "处置", "证据"],
            "来源": "主人令 2026-10-09"}


# ── 不开口闸（主人令 2026-10-09，第二次强调，故做成机器闸）────────────────────
#   「便利便捷是大众用户所需要的，千万别开口要求用户做什么，除了用户身份证账户需要登入才叫用户，
#     要不然严禁要求用户做事，把触手默认人类操作。」
#
# 三条落地：
#   ① **严禁开口**：凡是"要用户去做某事"的话（请你去点/麻烦你导出/你自己配一下/把文件发我…）一律驳回；
#   ② **唯一例外**：**用户身份/账户登录**（账号、实名、扫码、设备码、授权登录）—— 因为只有用户本人才有那个身份；
#      且即便例外，也要**我方主动跑流程**（生成设备码/二维码 → 触手代点 → 用户只做"确认身份"这一下）；
#   ③ **触手默认人类操作**：一切"本来要用户手点"的操作（网页导出/上传/点选/登录后操作/软件配置），
#      默认交给触手用**眼+手**去做（人类级操作），不需要用户动手。
ASK_PATTERNS: tuple = (r"请(你|您)?去", r"麻烦(你|您)", r"你自己(去|来)?", r"你需要(先|去|自己)", r"请你(先|帮我)?",
                       r"请提供", r"请把.*(发|传|放)", r"把.*(导出|发|传|拖).*(给我|过来)", r"你手动", r"手动(导|上|点)",
                       r"你先(配置|设置|安装|点|打开)", r"你来(点|配|导|上|操作)", r"需要你(配合|操作|动手)")
# 唯一例外：用户身份/账户登录（这些必须用户本人）
IDENTITY_EXCEPT: tuple = ("登录", "登陆", "账号", "账户", "身份证", "实名", "扫码", "设备码", "验证码",
                          "双重认证", "二次验证", "授权登录", "人脸", "指纹")
# 触手默认人类操作：这些"本来要人点"的动作，默认走触手（眼+手）
TENTACLE_DEFAULT: tuple = (
    dict(场景="网页导出/下载", 触手="core.tentacle_gui 找按钮+点击+盯下载", 要人做什么="不用人做"),
    dict(场景="网页上传/发布", 触手="触手在已登录页面点选上传", 要人做什么="仅在「对外发布」类需一次主人授权"),
    dict(场景="软件首次配置/启用插件", 触手="触手在界面里点开并保存", 要人做什么="不用人做"),
    dict(场景="登录后的一切点选", 触手="触手代点（含设备码流程）", 要人做什么="仅身份确认那一下（若必须）"),
    dict(场景="取件/搬运（云→本地）", 触手="触手导出后我方收仓", 要人做什么="不用人做"),
)


def check_ask(text: str) -> dict:
    """**不开口闸**：这段回复里有没有"要用户去做事"？除身份登录外一律驳回。"""
    import re as _re
    t = str(text or "")
    hit = [p for p in ASK_PATTERNS if _re.search(p, t)]
    if not hit:
        return {"通过": True, "口径": "没有要用户做事"}
    excepted = [k for k in IDENTITY_EXCEPT if k in t]
    if excepted:
        return {"通过": True, "例外": "用户身份/账户登录", "命中例外词": excepted[:3],
                "但仍要求": "我方主动跑流程：生成设备码/二维码 → 触手代点 → 用户只确认身份那一下"}
    return {"通过": False, "命中句式": hit[:3],
            "怎么办": "改写成：我自己做（触手人类操作）+ 说明我会做完再报读数；不要叫用户动手"}


def no_ask_rule() -> dict:
    return {"规则": "除用户身份/账户登录外，严禁开口要求用户做事；这类操作默认走触手（人类级操作）",
            "唯一例外": list(IDENTITY_EXCEPT),
            "触手默认": [dict(x) for x in TENTACLE_DEFAULT],
            "来源": "主人令 2026-10-09（第二次强调，故落成机器闸）"}


